def test_retyping_converts_the_values_already_stored(ctx):
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.set_metadata_for_images(db, image_ids, {"depth": "12"})

    meta.update_key(db, ctx["dataset_id"], "depth", value_type="number", unit="m")

    rows = db.query(ImageMetadata).filter_by(key="depth").all()
    assert all(row.value_num == 12.0 for row in rows)
    assert meta.get_key(db, ctx["dataset_id"], "depth").unit == "m"


def test_retyping_is_refused_when_a_stored_value_does_not_fit(ctx):
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.set_metadata_for_images(db, image_ids[:2], {"depth": "12"})
    meta.set_metadata_for_images(db, [image_ids[2]], {"depth": "shallow"})

    with pytest.raises(InvalidMetadataError) as excinfo:
        meta.update_key(db, ctx["dataset_id"], "depth", value_type="number")
    # The message has to name the offender, or there is no way to fix it.
    assert "shallow" in str(excinfo.value)
    assert meta.get_key(db, ctx["dataset_id"], "depth").value_type == "categorical"


def test_narrowing_a_vocabulary_is_refused_when_a_value_falls_outside(ctx):
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.set_metadata_for_images(db, image_ids[:2], {"site": "reef_a"})
    meta.set_metadata_for_images(db, [image_ids[2]], {"site": "reef_c"})

    with pytest.raises(InvalidMetadataError):
        meta.update_key(db, ctx["dataset_id"], "site", options=["reef_a", "reef_b"])


