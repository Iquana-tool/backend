"""The metadata type system and the CSV round trip.

Where the risk actually is:

  * **coercion** — the boundary between what a user typed and what the type says
    is representable. Getting this wrong either loses data or stores a value the
    type claims cannot exist,
  * **retyping an existing key**, which has to re-validate everything already
    stored and refuse rather than half-apply,
  * **rename/merge**, the repair for a key that got split by a typo, which walks
    straight into the (image_id, key) unique constraint if done naively,
  * **the CSV importer's dry run** — a preview is only worth approving if it is
    generated by the same code that then does the work.
"""
