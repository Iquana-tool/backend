@pytest.mark.parametrize("values,expected", [
    (["1", "0", "1"], MetadataValueType.BOOLEAN),
    (["yes", "no"], MetadataValueType.BOOLEAN),
    (["12", "13.5", "9"], MetadataValueType.NUMBER),
    (["2024-05-01", "2024-06-02"], MetadataValueType.DATE),
    (["reef_a", "reef_b", "reef_a", "reef_b"], MetadataValueType.CATEGORICAL),
])
def test_inference(values, expected):
    assert infer_type(values) == expected


def test_one_unparseable_value_keeps_the_whole_column_categorical():
    """A column of numbers with one "n/a" is not numeric — calling it numeric
    would lose that row on import."""
    assert infer_type(["12", "13", "n/a"]) == MetadataValueType.CATEGORICAL


def test_all_distinct_free_text_is_text_not_a_vocabulary():
    """Nothing repeats, so there are no groups to compare — offering it as a
    grouping would give one image per group."""
    values = [f"a note about specimen {i}" for i in range(10)]
    assert infer_type(values) == MetadataValueType.TEXT


def test_a_tiny_dataset_of_distinct_sites_is_still_a_vocabulary():
    """Three images with three sites must not be called free text just because
    nothing has had a chance to repeat yet."""
    assert infer_type(["reef_a", "reef_b", "reef_c"]) == MetadataValueType.CATEGORICAL


