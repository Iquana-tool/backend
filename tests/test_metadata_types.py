def test_number_keeps_its_spelling_and_gains_a_sort_value():
    """"12.0" and "12" are the same number to a filter, but the export should
    read the way it was typed."""
    assert coerce("12.0", MetadataValueType.NUMBER) == ("12.0", 12.0)


def test_a_non_number_is_rejected_rather_than_dropped():
    with pytest.raises(InvalidMetadataError):
        coerce("shallow", MetadataValueType.NUMBER)


def test_dates_canonicalise_to_iso_and_stay_date_only():
    canonical, numeric = coerce("01.05.2024", MetadataValueType.DATE)
    assert canonical == "2024-05-01"
    assert numeric > 0


def test_a_timestamp_keeps_its_precision():
    canonical, _ = coerce("2024-05-01T08:30:00+00:00", MetadataValueType.DATE)
    assert canonical.startswith("2024-05-01T08:30:00")


@pytest.mark.parametrize("written,expected", [
    ("yes", "true"), ("TRUE", "true"), ("1", "true"),
    ("no", "false"), ("f", "false"), ("0", "false"),
])
def test_booleans_canonicalise_however_they_were_written(written, expected):
    canonical, numeric = coerce(written, MetadataValueType.BOOLEAN)
    assert canonical == expected
    assert numeric == (1.0 if expected == "true" else 0.0)


def test_an_open_categorical_key_accepts_anything():
    assert coerce("reef_a", MetadataValueType.CATEGORICAL, []) == ("reef_a", None)


def test_a_locked_categorical_key_refuses_a_new_value():
    """Locking the vocabulary is what stops a typo becoming a fourth subgroup."""
    with pytest.raises(InvalidMetadataError):
        coerce("reef_c", MetadataValueType.CATEGORICAL, ["reef_a", "reef_b"])


