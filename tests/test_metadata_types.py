def test_numeric_range_filter(ctx):
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.ensure_key(db, ctx["dataset_id"], "depth", MetadataValueType.NUMBER)
    db.commit()
    for image_id, depth in zip(image_ids, ["2", "12", "30"]):
        meta.set_metadata_for_images(db, [image_id], {"depth": depth})

    matched = meta.filter_image_ids(db, ctx["dataset_id"], {"depth": {"min": 5, "max": 20}})
    assert matched == [image_ids[1]]


def test_an_open_ended_range_filters_on_one_side_only(ctx):
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.ensure_key(db, ctx["dataset_id"], "depth", MetadataValueType.NUMBER)
    db.commit()
    for image_id, depth in zip(image_ids, ["2", "12", "30"]):
        meta.set_metadata_for_images(db, [image_id], {"depth": depth})

    assert set(meta.filter_image_ids(db, ctx["dataset_id"], {"depth": {"min": 10}})) == {
        image_ids[1], image_ids[2]
    }


def test_date_range_filters_chronologically(ctx):
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.ensure_key(db, ctx["dataset_id"], "collected", MetadataValueType.DATE)
    db.commit()
    for image_id, day in zip(image_ids, ["2024-01-05", "2024-06-01", "2024-11-20"]):
        meta.set_metadata_for_images(db, [image_id], {"collected": day})

    from app.services.metadata_types import coerce as _coerce
    low = _coerce("2024-05-01", MetadataValueType.DATE)[1]
    high = _coerce("2024-07-01", MetadataValueType.DATE)[1]
    assert meta.filter_image_ids(
        db, ctx["dataset_id"], {"collected": {"min": low, "max": high}}
    ) == [image_ids[1]]


def test_text_contains_filter(ctx):
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.ensure_key(db, ctx["dataset_id"], "notes", MetadataValueType.TEXT)
    db.commit()
    meta.set_metadata_for_images(db, [image_ids[0]], {"notes": "bleached colony"})
    meta.set_metadata_for_images(db, [image_ids[1]], {"notes": "healthy"})

    assert meta.filter_image_ids(
        db, ctx["dataset_id"], {"notes": {"contains": "bleach"}}
    ) == [image_ids[0]]


def test_facets_report_the_range_of_an_ordered_key(ctx):
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.ensure_key(db, ctx["dataset_id"], "depth", MetadataValueType.NUMBER)
    db.commit()
    for image_id, depth in zip(image_ids, ["2", "12", "30"]):
        meta.set_metadata_for_images(db, [image_id], {"depth": depth})

    facet = meta.get_dataset_facets(db, ctx["dataset_id"])[0]
    assert facet["range"] == {"min": 2.0, "max": 30.0}
    assert facet["groupable"] is False, "a near-unique number is not a subgroup"
    # Ordered keys are listed in value order, not by popularity: 2, 12, 30 is a
    # scale; sorted by count it would be noise.
    assert [entry["value"] for entry in facet["values"]] == ["2", "12", "30"]


def test_a_declared_but_unused_key_still_appears(ctx):
    db = ctx["db"]
    meta.ensure_key(db, ctx["dataset_id"], "treatment", MetadataValueType.CATEGORICAL)
    db.commit()

    facets = meta.get_dataset_facets(db, ctx["dataset_id"])
    assert [facet["key"] for facet in facets] == ["treatment"]
    assert facets[0]["values"] == []


