def test_rename_moves_every_value(ctx):
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.set_metadata_for_images(db, image_ids, {"Site": "reef_a"})

    meta.rename_key(db, ctx["dataset_id"], "Site", "site")

    assert meta.get_metadata(db, image_ids[0]) == {"site": "reef_a"}
    assert meta.get_key(db, ctx["dataset_id"], "Site") is None
    assert meta.get_key(db, ctx["dataset_id"], "site") is not None


def test_rename_onto_an_existing_key_is_refused_without_merge(ctx):
    """Folding two vocabularies together silently is not a rename."""
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.set_metadata_for_images(db, [image_ids[0]], {"Site": "reef_a"})
    meta.set_metadata_for_images(db, [image_ids[1]], {"site": "reef_b"})

    with pytest.raises(InvalidMetadataError):
        meta.rename_key(db, ctx["dataset_id"], "Site", "site")


def test_merge_folds_the_split_key_back_together(ctx):
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.set_metadata_for_images(db, [image_ids[0]], {"Site": "reef_a"})
    meta.set_metadata_for_images(db, [image_ids[1]], {"site": "reef_b"})

    result = meta.rename_key(db, ctx["dataset_id"], "Site", "site", merge=True)

    assert result["renamed"] == 1
    assert meta.get_metadata(db, image_ids[0]) == {"site": "reef_a"}
    assert meta.get_metadata(db, image_ids[1]) == {"site": "reef_b"}
    assert [facet["key"] for facet in meta.get_dataset_facets(db, ctx["dataset_id"])] == ["site"]


def test_merge_on_an_image_carrying_both_keeps_the_renamed_one(ctx):
    """The caller named the source as the key to keep, so it wins the collision —
    and the old target row must be deleted before the rename to avoid tripping
    the (image_id, key) unique constraint."""
    db, image_id = ctx["db"], ctx["image_ids"][0]
    meta.set_metadata_for_images(db, [image_id], {"Site": "reef_a", "site": "reef_b"})

    result = meta.rename_key(db, ctx["dataset_id"], "Site", "site", merge=True)

    assert result["merged"] == 1
    assert meta.get_metadata(db, image_id) == {"site": "reef_a"}


def test_deleting_a_key_removes_its_values_and_its_declaration(ctx):
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.set_metadata_for_images(db, image_ids, {"site": "reef_a"})

    assert meta.delete_key_from_dataset(db, ctx["dataset_id"], "site") == 3
    assert meta.get_key(db, ctx["dataset_id"], "site") is None
    assert meta.get_metadata(db, image_ids[0]) == {}


