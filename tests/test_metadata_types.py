def test_export_of_an_untagged_dataset_is_the_template(ctx):
    """Starting from the export is what makes the filenames match on the way in."""
    csv_text = metadata_csv.export_csv(ctx["db"], ctx["dataset_id"])
    lines = csv_text.strip().splitlines()
    assert lines[0] == "file_name"
    assert lines[1:] == ["img_0.png", "img_1.png", "img_2.png"]


def test_export_then_import_is_a_round_trip(ctx):
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.set_metadata_for_images(db, image_ids[:2], {"site": "reef_a"})

    exported = metadata_csv.export_csv(db, ctx["dataset_id"])
    meta.delete_key_from_dataset(db, ctx["dataset_id"], "site")
    assert meta.get_metadata(db, image_ids[0]) == {}

    metadata_csv.import_csv(db, ctx["dataset_id"], exported.encode(), dry_run=False)
    assert meta.get_metadata(db, image_ids[0]) == {"site": "reef_a"}
    assert meta.get_metadata(db, image_ids[2]) == {}


def _csv(*lines: str) -> bytes:
    return "\n".join(lines).encode()


def test_dry_run_reports_without_writing(ctx):
    db = ctx["db"]
    content = _csv("file_name,site", "img_0.png,reef_a", "img_1.png,reef_b")

    result = metadata_csv.import_csv(db, ctx["dataset_id"], content, dry_run=True)

    assert result["matched"] == 2
    assert result["missing_from_file"] == ["img_2.png"]
    assert result["written"] == 0
    assert db.query(ImageMetadata).count() == 0


def test_unmatched_filenames_are_reported_not_guessed(ctx):
    db = ctx["db"]
    content = _csv("file_name,site", "img_0.png,reef_a", "nope.png,reef_b")

    result = metadata_csv.import_csv(db, ctx["dataset_id"], content, dry_run=True)

    assert result["matched"] == 1
    assert result["unmatched"] == ["nope.png"]


def test_import_infers_a_type_for_each_new_column(ctx):
    db = ctx["db"]
    content = _csv("file_name,depth,collected,site",
                   "img_0.png,12,2024-05-01,reef_a",
                   "img_1.png,30,2024-06-02,reef_b")

    result = metadata_csv.import_csv(db, ctx["dataset_id"], content, dry_run=True)

    by_key = {column["key"]: column for column in result["columns"]}
    assert by_key["depth"]["value_type"] == "number"
    assert by_key["collected"]["value_type"] == "date"
    assert by_key["site"]["value_type"] == "categorical"
    assert all(column["is_new"] for column in result["columns"])


