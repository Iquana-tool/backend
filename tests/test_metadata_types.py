def test_import_needs_the_write_permission(ctx, client):
    response = client("ann").post(
        f"/metadata/dataset/{ctx['dataset_id']}/import",
        files={"file": ("meta.csv", b"file_name,site\nimg_0.png,reef_a\n", "text/csv")},
    )
    assert response.status_code == 403


def test_key_declaration_over_http(ctx, client):
    dataset_id = ctx["dataset_id"]
    client("curator").post("/metadata/images",
                           json={"image_ids": ctx["image_ids"], "entries": {"depth": "12"}})

    response = client("curator").put(
        f"/metadata/dataset/{dataset_id}/keys/depth",
        json={"value_type": "number", "unit": "m"},
    )
    assert response.status_code == 200
    assert response.json()["key"] == {
        "key": "depth", "value_type": "number", "unit": "m",
        "options": [], "description": None,
    }

    listed = client("ann").get(f"/metadata/dataset/{dataset_id}/keys").json()["keys"]
    assert listed[0]["value_type"] == "number"


def test_retyping_over_http_is_a_422_naming_the_offender(ctx, client):
    dataset_id = ctx["dataset_id"]
    client("curator").post("/metadata/images",
                           json={"image_ids": [ctx["image_ids"][0]],
                                 "entries": {"depth": "shallow"}})

    response = client("curator").put(
        f"/metadata/dataset/{dataset_id}/keys/depth", json={"value_type": "number"}
    )
    assert response.status_code == 422
    assert "shallow" in response.json()["detail"]


def test_rename_over_http(ctx, client):
    dataset_id = ctx["dataset_id"]
    client("curator").post("/metadata/images",
                           json={"image_ids": ctx["image_ids"], "entries": {"Site": "reef_a"}})

    response = client("curator").post(
        f"/metadata/dataset/{dataset_id}/keys/Site/rename",
        json={"new_key": "site"},
    )
    assert response.status_code == 200
    assert response.json()["renamed"] == 3


def test_type_catalog_says_what_can_be_grouped(ctx, client):
    types = {entry["value_type"]: entry
             for entry in client("ann").get("/metadata/types").json()["types"]}
    assert types["categorical"]["groupable"] is True
    assert types["number"]["groupable"] is False
    assert types["number"]["ordered"] is True
