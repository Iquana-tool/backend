def test_writing_a_declared_numeric_key_fills_the_sort_column(ctx):
    db, image_id = ctx["db"], ctx["image_ids"][0]
    meta.ensure_key(db, ctx["dataset_id"], "depth", MetadataValueType.NUMBER)
    db.commit()
    meta.set_metadata_for_images(db, [image_id], {"depth": "12.5"})

    row = db.query(ImageMetadata).filter_by(image_id=image_id, key="depth").one()
    assert (row.value, row.value_num) == ("12.5", 12.5)


def test_a_value_the_type_rejects_fails_the_whole_batch(ctx):
    """Half a batch tagged is worse than none: the coercion runs before any write."""
    db, image_ids = ctx["db"], ctx["image_ids"]
    meta.ensure_key(db, ctx["dataset_id"], "depth", MetadataValueType.NUMBER)
    db.commit()

    with pytest.raises(InvalidMetadataError):
        meta.set_metadata_for_images(db, image_ids, {"depth": "shallow"})
    assert db.query(ImageMetadata).count() == 0


def test_writing_across_two_datasets_is_refused(ctx, tmp_path):
    """Keys are declared per dataset, so one batch has no single type to check."""
    db = ctx["db"]
    other = Datasets(name="other", description="", dataset_type="image",
                     folder_path=str(tmp_path), created_by="curator")
    db.add(other)
    db.flush()
    outsider = Images(dataset_id=other.id, file_name="x.png", file_path="x",
                      thumbnail_file_path="t", width=1, height=1, color_mode="RGB")
    db.add(outsider)
    db.commit()

    with pytest.raises(InvalidMetadataError):
        meta.set_metadata_for_images(db, [ctx["image_ids"][0], outsider.id],
                                     {"site": "reef_a"})


